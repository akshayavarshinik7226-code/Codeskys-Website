"""Dockerfiles Codeskys writes for framework projects (everything except "docker").

Students keep choosing one of the 14 frameworks; the student repository is never
modified. Instead of Coolify's own build packs (which build with host networking,
see buildpolicy), the generated compose file carries this Dockerfile inline
(``build.dockerfile_inline``) and builds the repository at the exact commit.

Safety properties, all checked again by ``composegen.assert_safe``:

* Only the base images in ``BASE_IMAGES`` appear in ``FROM`` lines.
* The student's install/build/start commands are only ever inserted as one
  JSON-encoded string inside an exec-form instruction
  (``RUN ["/bin/sh", "-c", "<cmd>"]``), so they cannot add instructions, flags or
  parser directives. Commands containing line breaks, NUL or the build flags
  buildpolicy refuses are rejected outright.
* Containers run as an unprivileged user. Static sites are served by
  nginx-unprivileged on port 8080 (no capability to bind 80 is ever granted).
"""
from __future__ import annotations

import json
import re

from .gitinfo import FRAMEWORKS

MARKER = "# Generated by Codeskys"
# The project's "Node version" setting (shown in the UI, default 20.x) picks the image.
NODE_IMAGES = {"18": "node:18-bookworm-slim", "20": "node:20-bookworm-slim", "22": "node:22-bookworm-slim"}
DEFAULT_NODE = "20"
NODE_IMAGE = NODE_IMAGES[DEFAULT_NODE]
PYTHON_IMAGE = "python:3.12-slim-bookworm"
STATIC_IMAGE = "nginxinc/nginx-unprivileged:1.27-alpine"
BASE_IMAGES = frozenset({*NODE_IMAGES.values(), PYTHON_IMAGE, STATIC_IMAGE})
STATIC_PORT = 8080

_PATH = re.compile(r"^[A-Za-z0-9._-]+(?:/[A-Za-z0-9._-]+)*$")
_FLAGS = re.compile(r"--(network|security|device)\b", re.I)
PYTHON_FRAMEWORKS = {"flask", "django"}

# SPA-friendly static server: unknown paths fall back to index.html, no server tokens.
# Written inside single quotes so the shell leaves nginx's $uri alone.
# absolute_redirect off: behind Caddy/Traefik a redirect must never name the internal port.
_NGINX_CONF = ("server { listen 8080; root /usr/share/nginx/html; index index.html; server_tokens off; "
               "absolute_redirect off; location / { try_files $uri $uri/index.html $uri.html /index.html; } }")


class DockerfileError(ValueError):
    """A project setting that cannot go into a generated Dockerfile. Safe to show."""


def _command(value: str, what: str) -> str:
    value = (value or "").strip()
    if len(value) > 500 or any(c in value for c in "\r\n\x00"):
        raise DockerfileError(f"The {what} must be a single line of at most 500 characters.")
    if _FLAGS.search(value):
        raise DockerfileError(f"The {what} may not contain --network, --security or --device.")
    return value


def _path(value: str, what: str) -> str:
    value = (value or "").strip().strip("/")
    if value and (not _PATH.match(value) or ".." in value.split("/")):
        raise DockerfileError(f"The {what} must be a relative path inside the repository.")
    return value


def _run(cmd: str) -> str:
    return "RUN " + json.dumps(["/bin/sh", "-c", cmd])


def _cmd(cmd: str) -> str:
    return "CMD " + json.dumps(["/bin/sh", "-c", "exec " + cmd])


def _find_site(root: str) -> str:
    """Shell script: copy the folder holding index.html to /site. The shallowest one
    wins (Angular 17+ builds into dist/<name>/browser). ``root`` is a validated path."""
    return (
        f'set -e; d={root}; '
        '[ -f "$d/index.html" ] || '
        'd=$(dirname "$(find "$d" -name index.html -not -path "*/node_modules/*" '
        "| awk -F/ '{print NF, $0}' | sort -n | head -1 | cut -d' ' -f2-)\"); "
        '[ -f "$d/index.html" ] || { echo "Codeskys: no index.html found after the build" >&2; exit 1; }; '
        'mkdir -p /site && cp -a "$d"/. /site/'
    )


def settings(project) -> dict:
    """The effective, validated build settings of a framework project."""
    fw_id = project["framework"]
    if fw_id == "docker" or fw_id not in FRAMEWORKS:
        raise DockerfileError("This framework is built from the repository's own Dockerfile.")
    fw = FRAMEWORKS[fw_id]

    def pick(key, default):
        try:
            value = project[key]
        except (KeyError, IndexError):
            value = None
        return value if value not in (None, "") else default

    return {
        "framework": fw_id,
        "install": _command(pick("install_command", fw["install"]), "install command"),
        "build": _command(pick("build_command", fw["build"]), "build command"),
        "start": _command(pick("start_command", fw["start"]), "start command"),
        "output": _path(pick("output_dir", fw["output"]), "output directory"),
        "static": bool(fw["static"]),
        "port": STATIC_PORT if fw["static"] else int(pick("port", fw["port"])),
        # Python projects and plain static HTML never run Node: their setting is ignored.
        "node_image": (None if fw_id in PYTHON_FRAMEWORKS or (fw["static"] and not (fw["install"] or fw["build"]))
                       else _node_image(pick("node_version", DEFAULT_NODE))),
    }


def _node_image(version) -> str:
    major = str(version).strip().lower().removeprefix("v").split(".")[0]
    if major not in NODE_IMAGES:
        raise DockerfileError(f"Node version {str(version)[:20]} is not available. Choose "
                              + ", ".join(f"{v}.x" for v in NODE_IMAGES) + " in Project → Settings.")
    return NODE_IMAGES[major]


def generate(project) -> tuple[str, int]:
    """Return (Dockerfile text, port the app listens on)."""
    s = settings(project)
    lines = [MARKER + f" for framework '{s['framework']}'. Do not edit: regenerated on every deploy."]
    if s["static"]:
        if s["install"] or s["build"]:
            lines += [f"FROM {s['node_image']} AS build", "WORKDIR /app", "COPY . .",
                      "ENV CI=true NODE_ENV=production NPM_CONFIG_PRODUCTION=false"]
            lines += [_run(s["install"])] if s["install"] else []
            lines += [_run(s["build"])] if s["build"] else []
            lines += [_run(_find_site("/app/" + s["output"] if s["output"] else "/app")),
                      f"FROM {STATIC_IMAGE}", "COPY --from=build /site /usr/share/nginx/html"]
        else:
            lines += [f"FROM {STATIC_IMAGE}", f"COPY {s['output'] or '.'}/ /usr/share/nginx/html/"]
        lines += ["USER root",
                  _run(f"printf '%s\\n' '{_NGINX_CONF}' > /etc/nginx/conf.d/default.conf"),
                  "USER 101", f"EXPOSE {STATIC_PORT}"]
        return "\n".join(lines) + "\n", STATIC_PORT

    if not s["start"]:
        raise DockerfileError("A start command is required for this framework.")
    if s["framework"] in PYTHON_FRAMEWORKS:
        lines += [f"FROM {PYTHON_IMAGE}", "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1",
                  _run("useradd --create-home --uid 10001 app"), "WORKDIR /app", "COPY --chown=10001:10001 . ."]
        lines += [_run(s["install"])] if s["install"] else []
        lines += ["USER 10001"]
        lines += [_run(s["build"])] if s["build"] else []
    else:
        lines += [f"FROM {s['node_image']}", "ENV CI=true NPM_CONFIG_PRODUCTION=false", "WORKDIR /app",
                  _run("chown node:node /app"), "USER node", "COPY --chown=node:node . ."]
        lines += [_run(s["install"])] if s["install"] else []
        lines += [_run(s["build"])] if s["build"] else []
        lines += ["ENV NODE_ENV=production"]
    lines += [f"ENV PORT={s['port']} HOST=0.0.0.0 HOSTNAME=0.0.0.0", f"EXPOSE {s['port']}", _cmd(s["start"])]
    return "\n".join(lines) + "\n", s["port"]
